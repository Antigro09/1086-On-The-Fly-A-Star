#!/usr/bin/env node
// Dependency-free tests of the browser importer contract; no server/browser needed.
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {webcrypto} from 'node:crypto';
import assert from 'node:assert/strict';
if (!globalThis.crypto) Object.defineProperty(globalThis,'crypto',{value:webcrypto});
const here=path.dirname(fileURLToPath(import.meta.url));
const source=fs.readFileSync(path.resolve(here,'../../src/dashboard/resources/dashboard/field-import.js'),'utf8');
const api=await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
const fixture=JSON.parse(fs.readFileSync(path.join(here,'synthetic-approved.json')));
const expected=JSON.parse(fs.readFileSync(path.join(here,'expected-digests.json')));
const png=fs.readFileSync(path.join(here,'synthetic-top-down.png'));
const clone=()=>JSON.parse(JSON.stringify(fixture));
let checks=0;
const check=(condition,message)=>{assert.ok(condition,message);checks++;};
check(api.FIELD_MAP_VERSION==='frc-field-map/1','exact schema version');
check(await api.sha256(png)===expected.image_sha256,'image hash golden');
check(await api.canonicalContentDigest(fixture)===expected.content_sha256,'canonical golden approval');
check((await api.validateFieldMap(fixture)).valid,'approved golden valid');
check(api.inspectRaster(png).width===400&&api.inspectRaster(png).height===200,'PNG encoded dimensions');
check(JSON.stringify(api.transformPixel(fixture.calibration.image_to_field,[0,200]))==='[0,0]','origin transform');
check(JSON.stringify(api.transformPixel(fixture.calibration.image_to_field,[400,0]))==='[8,4]','top-right transform');
check(fixture.obstacles[0].vertical_range_m===null,'unknown height remains null');
check(fixture.obstacles[0].holes.length===1,'physical hole unchanged');
const approved=clone();approved.approval.content_sha256='0'.repeat(64);
check(!(await api.validateFieldMap(approved)).valid,'incorrect content digest rejected');
const edited=clone();edited.obstacles[0].outer[1][0]=5.1;
check(!(await api.validateFieldMap(edited)).valid,'geometry edit invalidates digest');
const changedImage=clone();changedImage.image.sha256='a'.repeat(64);
check(!(await api.validateFieldMap(changedImage)).valid,'image identity edit invalidates digest');
const draft=api.invalidateFieldMap(clone());
check(draft.map.revision===2&&draft.approval.state==='draft'&&draft.approval.content_sha256===null,'revision invalidates approval');
check(draft.boundary.review.state==='draft'&&draft.obstacles[0].review.state==='draft','all polygon reviews invalidated');
check((await api.validateFieldMap(draft)).valid,'valid draft accepted for display');
const bad=async(mutator,message)=>{const doc=clone();mutator(doc);check(!(await api.validateFieldMap(doc)).valid,message);};
await bad(d=>d.calibration.model='homography','perspective unsupported');
await bad(d=>d.calibration.image_to_field[6]=0.01,'non-affine matrix rejected');
await bad(d=>d.calibration.image_to_field[4]=0,'singular transform rejected');
await bad(d=>d.calibration.image_to_field[0]=Infinity,'nonfinite transform rejected');
await bad(d=>{d.calibration.image_to_field[0]=1e308;d.calibration.image_to_field[4]=1e308;},'overflow determinant rejected');
await bad(d=>d.map.width_m=NaN,'nonfinite field rejected');
await bad(d=>d.map.frame='y_up','unconverted field frame rejected');
await bad(d=>d.map.revision=0,'invalid revision');
await bad(d=>d.image.file_name='https://outside/image.png','external image reference rejected');
await bad(d=>d.image.file_name='../image.png','directory traversal basename rejected');
await bad(d=>d.image.width_px=100000,'image dimension bound');
await bad(d=>d.image.mime_type='image/svg+xml','active SVG rejected');
await bad(d=>d.calibration.independent_check_points=[],'independent check required');
await bad(d=>d.calibration.control_points.push(d.calibration.control_points[0]),'duplicate fit pixel rejected');
await bad(d=>d.calibration.independent_check_points.push(d.calibration.independent_check_points[0]),'duplicate independent pixel rejected');
await bad(d=>d.calibration.independent_check_points=[d.calibration.control_points[0]],'fitted point cannot be independent');
await bad(d=>d.calibration.fit_error_m=.3,'fit residual consistency');
await bad(d=>d.calibration.independent_check_error_m=.3,'independent residual consistency');
await bad(d=>d.boundary.review.reviewed_revision=2,'stale shape review');
await bad(d=>d.approval.reviewed_revision=2,'stale map review');
await bad(d=>d.obstacles[0].outer.reverse(),'CCW outer winding required');
await bad(d=>d.obstacles[0].holes[0].reverse(),'CW hole winding required');
await bad(d=>d.obstacles[0].outer.pop(),'explicit ring closure required');
await bad(d=>d.obstacles[0].outer=[[3,1],[5,3],[3,3],[5,1],[3,1]],'self intersection rejected');
await bad(d=>d.obstacles[0].holes=[[[2,1],[2,2],[3,2],[3,1],[2,1]]],'hole outside outer rejected');
await bad(d=>d.obstacles[0].holes.push(d.obstacles[0].holes[0]),'overlapping holes rejected');
await bad(d=>d.obstacles[0].outer[1]=[9,1],'field-bound violation rejected');
await bad(d=>d.obstacles[0].vertical_range_m={min:2,max:1},'inverted known height rejected');
await bad(d=>d.obstacles.push(d.obstacles[0]),'duplicate obstacle id rejected');
await bad(d=>d.obstacles[0].private_note='x','unknown fields rejected');
await bad(d=>d.source.label='x'.repeat(1025),'string length bound');
await bad(d=>d.obstacles=Array.from({length:17},(_,i)=>({...d.obstacles[0],id:'x'+i,outer:Array.from({length:257},()=>[3,1])})),'excess total vertices rejected before intersections');
check(api.validateFieldMapGeometry(null).length>0,'null map safely rejected');
check(api.validateFieldMapGeometry({...clone(),obstacles:[null]}).length>0,'malformed polygon safely rejected');
const unicodeOrder=api.canonicalFieldMapContent({'\u{10000}':1,'\uE000':2,approval:null});
check(unicodeOrder.indexOf('\uE000')<unicodeOrder.indexOf('\u{10000}'),'supplementary/BMP keys use Unicode codepoint order');
await bad(d=>d.source.label='\uD800','unpaired Unicode surrogate rejected');
const minusZero=clone();minusZero.calibration.image_to_field[1]=-0;
check(await api.canonicalContentDigest(minusZero)===expected.content_sha256,'negative zero normalized');
const reorder=Object.fromEntries(Object.entries(fixture).reverse());
check(await api.canonicalContentDigest(reorder)===expected.content_sha256,'key ordering canonical');
let bounded=false;try{api.inspectRaster(new Uint8Array(8*1024*1024+1));}catch{bounded=true;}
check(bounded,'encoded byte bound');
const huge=Buffer.from(png);huge.writeUInt32BE(8193,16);bounded=false;try{api.inspectRaster(huge);}catch{bounded=true;}
check(bounded,'encoded dimension checked before decode');
const pixels=new Uint8ClampedArray(20*10*4).fill(255);
for(let y=2;y<8;y++)for(let x=5;x<15;x++){const i=(y*20+x)*4;pixels[i]=pixels[i+1]=pixels[i+2]=0;}
const boxes=api.suggestRegions(pixels,20,10,100,10);
check(boxes.length===1&&boxes[0].minX===5&&boxes[0].maxX===15,'bounded connected-region outline');
check(api.suggestRegions(pixels,20,10,100,100).length===0,'minimum connected area respected');
check(api.suggestRegions(pixels,20,10,100,10,0).length===0,'candidate count bounded');
console.log('Field-map contract: '+checks+' checks passed');
